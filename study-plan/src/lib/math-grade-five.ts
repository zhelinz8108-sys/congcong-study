const makeDetails = (
  explanation: string,
  examPoints: string[],
  examples: MathExample[]
): MathKnowledgeDetails => ({
  explanation,
  examPoints,
  examples,
});

const getUnitTopic = (code?: string): string => {
  const unit = code?.split(".")[0];
  switch (unit) {
    case "1":
      return "简易方程";
    case "2":
      return "折线统计图";
    case "3":
      return "因数与倍数";
    case "4":
      return "分数的意义和性质";
    case "5":
      return "分数加法和减法";
    case "6":
      return "长方体和正方体";
    case "7":
      return "分数乘法";
    case "8":
      return "整理与复习";
    default:
      return "综合复习";
  }
};

