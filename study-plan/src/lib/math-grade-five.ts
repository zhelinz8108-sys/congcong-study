const getSupplementExamples = (title: string, code?: string): MathExample[] => {
  if (title.includes("折线统计图")) return getStatisticsExamples(title);
  if (
    title.includes("因数") ||
    title.includes("倍数") ||
    title.includes("质数") ||
    title.includes("合数") ||
    title.includes("质因数") ||
    title.includes("公倍数")
  ) {
    return getFactorMultipleExamples(title);
  }
  if (
    title.includes("分数的意义") ||
    title.includes("分数与除法") ||
    title.includes("真分数") ||
    title.includes("假分数") ||
    title.includes("分数与小数") ||
    title.includes("约分") ||
    title.includes("通分") ||
    title.includes("分数的大小比较") ||
    title.includes("几分之几")
  ) {
    return getFractionMeaningExamples(title);
  }
  if (
    title.includes("分数加") ||
    title.includes("分数、减法") ||
    title.includes("加、减法") ||
    title.includes("连加") ||
    title.includes("连减") ||
    title.includes("加减混合")
  ) {
    return getFractionAddSubExamples(title);
  }
  if (
    title.includes("长方体") ||
    title.includes("正方体") ||
    title.includes("表面积") ||
    title.includes("体积") ||
    title.includes("容积") ||
    title.includes("涂色")
  ) {
    return getCuboidExamples(title);
  }
  if (
    title.includes("分数乘法") ||
    title.includes("分数与整数相乘") ||
    title.includes("分数与分数相乘") ||
    title.includes("分数连乘") ||
    title.includes("倒数") ||
    title.includes("实际问题")
  ) {
    return getFractionMultiplicationExamples(title);
  }
  if (title.includes("整理") || title.includes("练习") || title.includes("核心素养") || title.includes("综合")) {
    return getReviewExamples(title, code);
  }

  return getEquationExamples(title);
};

const ensureFiveExamples = (
  details: MathKnowledgeDetails,
  title: string,
  code?: string
): MathKnowledgeDetails => {
  const supplementalExamples = getSupplementExamples(title, code);
  const examples = [...details.examples, ...supplementalExamples].slice(0, 5);

  return {
    ...details,
    examples,
  };
};

const point = (code: string, title: string, page: number): MathKnowledgePoint => ({
  code,
  title,
  page,
  details: ensureFiveExamples(buildMathDetails(title, code), title, code),
});

const review = (title: string, page: number): MathKnowledgePoint => ({
  title,
  page,
  review: true,
  details: ensureFiveExamples(buildMathDetails(title), title),
});

