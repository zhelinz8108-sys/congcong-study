export const getChineseCurriculumByStage = (stage: ChineseStageKey) =>
  CHINESE_CURRICULUM.filter((grade) => grade.stage === stage);

export const countChineseTopics = (stage?: ChineseStageKey, module?: ChineseModuleKey) =>
  CHINESE_CURRICULUM.filter((grade) => (stage ? grade.stage === stage : true)).reduce(
    (total, grade) =>
      total +
      grade.modules
        .filter((blockItem) => (module ? blockItem.module === module : true))
        .reduce((sum, blockItem) => sum + blockItem.topics.length, 0),
    0
  );
